Sabarinathan Jewellers® · 166, Nethaji Road, Madurai
Effective from: 10 July 2023

This policy applies to all staff of Sabarinathan Jewellers. Please read it carefully and sign at the end to confirm that you have understood and accept it.

1. WORKING HOURS
- Women staff: reporting 9:30 AM, leaving 8:30 PM
- Men staff: reporting 9:30 AM, leaving until the shop closes

2. LUNCH BREAK AND REFRESHMENTS
- Lunch break is 1 hour.
- Staff are recommended to bring their lunch from home.
- You must sign out on the biometric when you leave for lunch and sign in again when you return.
Tea, coffee and snacks
- Tea or coffee is provided by the shop every morning and evening.
- Snacks are provided every evening.

3. BIOMETRIC ATTENDANCE
- Biometric sign-in is compulsory every time you enter the shop.
- You must sign out every time you go out — including for lunch — and sign in when you return.
- All your punches are recorded and can be seen in the Mybuddy attendance app. Please check your punches regularly and report any mistake to the management the same day.
Going out for personal matters
- If you need to go out of the shop for a personal matter, you must inform the management first, punch out on the biometric when leaving, and punch in when you are back.

4. LATE COMING
- Reporting time is 9:30 AM, with a grace time up to 9:50 AM.
- If you arrive after 9:50 AM without applying for permission in the Mybuddy app, ₹1 will be deducted for every minute late (counted from 9:50 AM).
  Example: arriving at 10:05 AM without permission = 15 minutes late = ₹15 deducted.
- No deduction is made if permission was applied for and approved in the Mybuddy app.

5. PERMISSION
- 2 permissions per month are allowed, each up to 2 hours.
- Permission must be applied for in the Mybuddy app before you use it.
- Time taken beyond the approved permission will be treated as late coming.

6. LEAVE
- 3 days of paid leave are allowed every month.
- If you take more than 3 days of leave in a month, salary will be deducted for each extra day based on your salary.
  Per-day salary = Monthly salary ÷ 30
  Example: monthly salary ₹15,000 and 5 days of leave → 2 extra days × ₹500 = ₹1,000 deducted.
- Please inform the management in advance for planned leave.
Emergency leave
- In case of an emergency, apply in the Leave Request option in the Mybuddy app as soon as possible, and inform the management by phone.
- Emergency leave is counted within your 3 days of paid leave; anything beyond 3 days is deducted as above.

7. WEEK OFF
- Week off must be applied for in the Mybuddy app in advance — not on the same day.
- You must also mention your week off in the everyday staff meeting, so the team can plan floor coverage.
- A week off taken without applying in the app beforehand and without mentioning it in the meeting will be treated as leave.
Days to avoid for week off
- Week off should usually not be taken on Saturdays, Sundays or Wednesdays, as many customers buy gold and silver on these days and the shop needs full staff.
Festival and peak season
- No leave or week off during Akshaya Tritiya, Deepavali and Pongal festival periods.
- During the wedding season, leave or week off is allowed only with special approval from the management.

8. NO OUTSIDE BUSINESS
- While working at Sabarinathan Jewellers, staff must not do any other business outside the shop — whether jewellery or any other trade, directly or through others.
- Doing outside business is breaking the shop rules and will be treated as a serious violation by the management.

9. COMMISSION AND INCENTIVES
- Own customers: if you bring your own customers to the shop, you can earn a commission as per the transaction agreement relevant to that customer's business.
- Sales incentive: an incentive is given on all sales happening in the shop. The incentive is calculated according to the rules set in the Mybuddy app, where you can see your incentive details.

10. SALARY PAYMENT
- Salary is credited every month on the 3rd or 4th day of the month.
- Salary is paid only by bank transfer to your bank account.
- Please fill in your correct bank details in the acceptance form. The shop is not responsible for delays caused by wrong bank details, and any change in your bank account must be informed to the management in writing.
Salary advance
- Please avoid asking for a salary advance unless it is a genuine emergency.
- Salary advance rules are decided by the management for each individual, case by case.

11. CONDUCT AND DISCIPLINE
Alcohol and substances
- Coming to the showroom after drinking alcohol or taking any other substance is a violation of the shop rules.
- Consuming alcohol or any substance inside the shop premises is strictly not allowed.
Respectful behaviour between staff
- Both men and women work together in the shop. Each and every staff member is responsible for maintaining proper physical distance and decorum at all times — with colleagues and with customers.
- The management will not tolerate any sexual misconduct or harassment of any kind — by words, gestures, messages or physical behaviour. Strict action will be taken against anyone involved.
- Any staff member who faces or sees such behaviour should report it to the management immediately. Complaints will be handled confidentially.
Behaviour in the showroom
- Staff must not gather together and laugh or chat loudly in the showroom.
- No verbal or physical fights of any kind inside the shop.
- Do not speak harsh words to colleagues or customers. Always speak politely and respectfully.
No money lending between staff
- Staff must not lend or borrow money with other staff — whether as a loan or on interest.
- No one's job is permanent. If a staff member borrows money and leaves the shop, the shop is not responsible for that money in any way.
Theft
- If any staff member is involved in theft, the management will take necessary action, including a police complaint and recovery of the stolen items or money.
Mobile phones
- You may carry your mobile phone, but no personal phone use while attending customers on the sales floor.
Confidentiality and social media
- Customer details — names, phone numbers and purchase details — must not be shared with anyone, and must not be taken or used after you leave the job.
- Shop rates, stock, supplier and business details must be kept confidential.
- Do not post shop jewellery or photos on your personal social media without the management's permission.
Cash and payments
- Every customer payment — cash, UPI or card — must go only through the billing counter, never to a staff member personally.
- Never accept customer money into your personal UPI or bank account.
- No cash, gifts or tips may be accepted from customers without the management's approval.
Uniform and grooming
- Once given, the uniform must be worn neat and clean every working day.
- Only on Tuesdays, colour dress is allowed instead of the uniform.
- Maintain a clean, tidy appearance and hair at all times.
- Avoid wearing heavy personal jewellery at work, so that it is not mixed up with shop stock.
Please keep this in mind at all times.

12. RESIGNATION AND TERMINATION
Probation period
- Every new staff member will be on probation for the first 3 months from the date of joining.
- During probation, either the staff member or the management can end the job with 1 week's notice.
- After probation is completed, the 1-month notice rules below apply.
- Uniforms will be provided after the probation period is completed.
If you decide to leave the job
- You must give the management 1 month's prior notice.
- During the notice period, you must help the shop find and train a replacement for your role.
If the management decides to end your employment
- Apart from cases of disciplinary action, the management will inform you 1 month in advance before termination.
Disciplinary action
- If disciplinary action is taken against you for breaking the shop rules (for example, outside business, alcohol or substances, sexual misconduct or other serious violations), termination will be immediate, without notice.
Absent without informing (absconding)
- If you are absent for 7 continuous days without informing the management, it will be treated as leaving the job without notice.
- In such cases, your salary and original documents will be held until the final settlement is completed.
Final settlement
Your last salary will be paid only after all of the following are completed:
- Handover of work — your duties and customers handed over properly.
- Stock check — the count and weight of the stock under your care verified.
- Return of shop items — ID card, uniform, keys and any other shop items returned.
- Clearing of dues — any salary advance or recovery amount adjusted from the final salary.
- Training and finding a replacement, if the management or HR asks for it.
Return of original documents
- Your original documents submitted at joining will be returned along with your final salary settlement, after all dues and any recovery are cleared.

13. SHOP CLEANLINESS AND STOCK RESPONSIBILITY
Cleanliness
- Each and every staff member is responsible for keeping the shop clean — including cleaning the trays, glasses, mirrors, chairs and jewellery.
Stock count and weight
- Each staff member is responsible for the count and weight of the gold and silver products in their care.
- Whenever you show items to customers or take them out for cleaning, be careful about the count, and make sure every piece is returned to its place.
- Always stay alert and watch out for thieves, especially when many items are open on the counter.
Missing or short stock
- If any item goes missing or the weight is short in the stock under your care, the management will investigate first — using CCTV footage, stock records and billing details.
- After the investigation, the management will decide on recovery of the loss and any action, case by case.
CCTV and security checks
- The whole shop is under CCTV, and the footage can be used in any investigation.
- Personal bags and belongings must be kept in the locker or the place fixed by the management — not at the counter.
- Staff bags and belongings may be checked when leaving the shop.
Opening and closing stock
- Taking the physical opening stock when the shop opens and the physical closing stock before it closes is part of your daily job.
Sales and walkouts
- Whenever you sell an item, it must be reported for billing and to the management with the estimation.
- If a customer walks out without buying, take their customer details in the walkout note.
- After every sale, ask the customer to give a Google review for the shop.
- Speak to every customer about our chit / gold savings schemes and explain how they can join.
Reporting
- If anything wrong is happening in the shop, it is your responsibility to inform the management immediately.

